      "chart <- chart + scale_x_date(date_breaks = date_breaks, date_labels = date_labels, expand = expansion(mult = c(0.05, 0.15)))"
    )
  } else if (is.numeric(data[[x]])) {
    paste0("chart <- chart + scale_x_continuous(breaks = sort(unique(chart_data$`", x, "`)))")
