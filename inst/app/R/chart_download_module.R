  )
  axis_code <- if (inherits(data[[x]], "Date")) {
    c(
      "date_span <- as.numeric(diff(range(chart_data$date, na.rm = TRUE)))",
      "date_breaks <- if (date_span > 1825) \"1 year\" else if (date_span > 365) \"6 months\" else if (date_span > 90) \"1 month\" else \"1 week\"",
