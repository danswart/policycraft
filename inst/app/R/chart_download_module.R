  )
}

mapping_code <- function(mapping) {
  if (is.null(mapping) || !length(mapping)) return(NULL)
  entries <- vapply(names(mapping), function(name) {
    expression <- rlang::get_expr(mapping[[name]])
    paste0(name, " = ", paste(deparse(expression, width.cutoff = 120L), collapse = " "))
  }, "")
  paste0("ggplot2::aes(", paste(entries, collapse = ", "), ")")
}

geom_function <- function(layer) {
  functions <- c(
    GeomCol = "ggplot2::geom_col",
    GeomHline = "ggplot2::geom_hline",
    GeomLine = "ggplot2::geom_line",
    GeomPoint = "ggplot2::geom_point",
    GeomRichText = "ggtext::geom_richtext",
    GeomSegment = "ggplot2::geom_segment",
    GeomText = "ggplot2::geom_text",
    GeomVline = "ggplot2::geom_vline"
  )
  match <- intersect(class(layer$geom), names(functions))
  if (!length(match)) return(NA_character_)
  unname(functions[[match[1]]])
}

layer_parameter_code <- function(layer) {
  # aes_params are the explicit fixed aesthetics supplied by the app. Retain a
  # small set of meaningful geom parameters while dropping ggplot2 defaults.
  keep_geom <- c(
    "arrow", "check_overlap", "label.padding", "label.margin", "label.r",
    "lineend", "linejoin", "parse"
  )
  parameters <- c(
    layer$aes_params,
    layer$geom_params[intersect(names(layer$geom_params), keep_geom)]
  )
  parameters <- parameters[!duplicated(names(parameters))]
  parameters <- parameters[!vapply(parameters, is.null, logical(1))]
  parameters <- parameters[!vapply(parameters, is.function, logical(1))]
  if (!length(parameters)) return(character(0))
  vapply(names(parameters), function(name) {
    paste0(name, " = ", code_value(parameters[[name]]))
  }, "")
}

plot_labels_code <- function(plot) {
  wanted <- c("title", "subtitle", "caption", "x", "y")
  labels <- plot$labels[intersect(wanted, names(plot$labels))]
  labels <- labels[vapply(labels, function(x) is.null(x) ||
    (is.atomic(x) && length(x) == 1L), logical(1))]
  if (!length(labels)) return(NULL)
  values <- vapply(names(labels), function(name) {
    paste0(name, " = ", code_value(labels[[name]]))
  }, "")
  paste0("ggplot2::labs(\n    ", paste(values, collapse = ",\n    "), "\n  )")
}

resolved_layer_export <- function(layer, plot, layer_number) {
  data <- if (inherits(layer$data, "waiver")) plot$data else layer$data
  data <- as.data.frame(data)
  mapping <- if (isTRUE(layer$inherit.aes)) plot$mapping else list()
  for (name in names(layer$mapping)) mapping[[name]] <- layer$mapping[[name]]

  exported_mapping <- character(0)
  if (length(mapping)) {
    for (name in names(mapping)) {
      value <- tryCatch(
        rlang::eval_tidy(mapping[[name]], data = data),
        error = function(e) NULL
      )
      if (!is.null(value) && (length(value) == 1L || length(value) == nrow(data))) {
        column <- paste0(".layer_", layer_number, "_", name)
        data[[column]] <- rep(value, length.out = nrow(data))
        exported_mapping <- c(exported_mapping, paste0(name, " = ", column))
      } else {
        expression <- rlang::get_expr(mapping[[name]])
        exported_mapping <- c(
          exported_mapping,
          paste0(name, " = ", paste(deparse(expression, width.cutoff = 120L), collapse = " "))
        )
      }
    }
  }

  list(
    data = data,
    mapping = if (length(exported_mapping)) {
      paste0("ggplot2::aes(", paste(exported_mapping, collapse = ", "), ")")
    } else {
      NULL
    }
  )
}

plot_scale_code <- function(plot) {
  data <- if (inherits(plot$data, "waiver")) data.frame() else plot$data
  mapping_names <- names(plot$mapping)
  x_name <- if ("x" %in% mapping_names) {
    as.character(rlang::get_expr(plot$mapping$x))
  } else {
    NULL
  }
  x_values <- if (!is.null(x_name) && x_name %in% names(data)) data[[x_name]] else NULL

  calls <- character(0)
  if (inherits(x_values, "Date")) {
    calls <- c(calls, "ggplot2::scale_x_date(date_labels = \"%Y-%m-%d\")")
  } else if (is.numeric(x_values)) {
    calls <- c(calls, paste0(
      "ggplot2::scale_x_continuous(breaks = ",
      code_value(sort(unique(x_values[is.finite(x_values)]))), ")"
    ))
  }

  colour_mapped <- "colour" %in% mapping_names || "color" %in% mapping_names ||
    any(vapply(plot$layers, function(layer) {
      any(c("colour", "color") %in% names(layer$mapping))
    }, logical(1)))
  fill_mapped <- "fill" %in% mapping_names || any(vapply(plot$layers, function(layer) {
    "fill" %in% names(layer$mapping)
  }, logical(1)))
  if (colour_mapped) {
    calls <- c(calls, "ggplot2::scale_colour_manual(values = c(\"TRUE\" = \"red\", \"FALSE\" = \"blue\"))")
  }
  if (fill_mapped) {
    calls <- c(calls, "ggplot2::scale_fill_brewer(palette = \"Set2\")")
  }
  calls
}

# Create compact, readable ggplot2 source. Chart and layer data are emitted as
# ordinary data frames; reactive environments and other Shiny session state are
# deliberately excluded.
ggplot_code_lines <- function(plot, chart_name = "chart") {
  if (!inherits(plot, "ggplot")) {
    stop("The chart code download requires a ggplot object.", call. = FALSE)
  }
  semantic <- semantic_chart_code(plot, chart_name)
  if (!is.null(semantic)) return(semantic)

  chart_data <- if (inherits(plot$data, "waiver")) data.frame() else as.data.frame(plot$data)
  lines <- c(
    "# Generated by policycraft from the chart currently shown in the app.",
    "# The data and each ggplot2 layer are written explicitly for editing and learning.",
    "# Paste this file into a Quarto code cell, or source it from your report.",
    "",
    "library(ggplot2)",
    if (any(vapply(plot$layers, function(layer) inherits(layer$geom, "GeomRichText"), logical(1)))) "library(ggtext)" else NULL,
    "",
    paste0("# Chart: ", chart_name),
    "chart_data <- ",
    code_value(chart_data),
    ""
  )

  # Each layer receives explicit, resolved aesthetics below. Keeping the base
  # ggplot unmapped prevents quosure environments from leaking into the script.
  lines <- c(lines, "chart <- ggplot2::ggplot(data = chart_data)")

  layer_data_index <- 0L
  for (layer_number in seq_along(plot$layers)) {
    layer <- plot$layers[[layer_number]]
    geom <- geom_function(layer)
    if (is.na(geom)) next
    layer_data_index <- layer_data_index + 1L
    data_name <- paste0("layer_data_", layer_data_index)
    resolved <- resolved_layer_export(layer, plot, layer_number)
    lines <- c(
      lines,
      "",
      paste0("# Layer ", layer_number, ": ", sub(".*::", "", geom)),
      paste0(data_name, " <- "),
      code_value(resolved$data)
    )
    arguments <- c(paste0("data = ", data_name))
    if (!is.null(resolved$mapping)) arguments <- c(arguments, resolved$mapping)
    arguments <- c(arguments, "inherit.aes = FALSE")
    arguments <- c(arguments, layer_parameter_code(layer))
    layer_call <- paste0(geom, "(", paste(arguments, collapse = ", "), ")")
    lines <- c(lines, paste0("chart <- chart + ", layer_call))
  }

  additions <- c(
    plot_scale_code(plot),
    plot_labels_code(plot),
    "policycraft::policycraft_chart_theme()",
    "ggplot2::theme(axis.text.x = ggplot2::element_text(angle = 45, hjust = 1))"
  )
  lines <- c(
    lines,
    "",
    "# Scales, labels, and theme. These are safe places to customize the chart.",
    vapply(additions, function(addition) paste0("chart <- chart + ", addition), ""),
    "",
    "chart"
  )
  lines
}

chart_plot_ui <- function(id, height = "600px") {
  ns <- shiny::NS(id)
  shiny::plotOutput(ns("plot"), height = height)
}

chart_plot_server <- function(id, plot_reactive) {
  shiny::moduleServer(id, function(input, output, session) {
    output$plot <- shiny::renderPlot(plot_reactive())
  })
}

chart_download_server <- function(
  id,
  plot_reactive,
  filename_prefix,
  width = CHART_EXPORT_WIDTH_IN,
  height = CHART_EXPORT_HEIGHT_IN
) {
  shiny::moduleServer(id, function(input, output, session) {
    output$png <- shiny::downloadHandler(
      filename = function() paste0(filename_prefix, "_", Sys.Date(), ".png"),
      content = function(file) {
        ggplot2::ggsave(
          file,
          plot = plot_reactive(),
          device = "png",
          width = width,
          height = height,
          dpi = CHART_EXPORT_DPI,
          bg = "white"
        )
      }
    )

    output$svg <- shiny::downloadHandler(
      filename = function() paste0(filename_prefix, "_", Sys.Date(), ".svg"),
      content = function(file) {
        ggplot2::ggsave(
          file,
          plot = plot_reactive(),
          device = "svg",
          width = width,
          height = height,
          bg = "white"
        )
      }
    )

    output$pdf <- shiny::downloadHandler(
      filename = function() paste0(filename_prefix, "_", Sys.Date(), ".pdf"),
      content = function(file) {
        tryCatch(
          ggplot2::ggsave(
            file,
            plot = plot_reactive(),
            device = grDevices::cairo_pdf,
            width = width,
            height = height,
            bg = "white"
          ),
          error = function(e) {
            ggplot2::ggsave(
              file,
              plot = plot_reactive(),
              device = "pdf",
              width = width,
              height = height,
              bg = "white"
            )
          }
        )
      }
    )

    output$code <- shiny::downloadHandler(
      filename = function() paste0(filename_prefix, "_", Sys.Date(), ".R"),
      content = function(file) {
        writeLines(
          ggplot_code_lines(plot_reactive(), chart_name = filename_prefix),
          con = file,
          useBytes = TRUE
        )
      },
      contentType = "text/plain"
    )
  })
}
