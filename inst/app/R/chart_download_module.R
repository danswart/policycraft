# Convert a value to compact, executable R code without retaining environments.
code_value <- function(x) {
  paste(capture.output(dput(x)), collapse = "\n")
}

readable_data_code <- function(data, object = "chart_data") {
  data <- as.data.frame(data)
  keep <- !grepl("^\\.layer_", names(data))
  data <- data[keep]
  fields <- vapply(names(data), function(name) {
    paste0("  `", name, "` = ", code_value(data[[name]]))
  }, "")
  c(paste0(object, " <- data.frame("), paste0(fields, collapse = ",\n"), ",\n  check.names = FALSE\n)")
}

semantic_chart_code <- function(plot, chart_name) {
