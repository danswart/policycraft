  type <- sub("_expectation$", "", type)
  supported <- c("run", "line", "bar", "expectation", "trended", "trended_expectation", "cohort")
  if (!type %in% supported && !chart_name %in% c("expectation_chart", "trended_expectation_chart")) return(NULL)
  if (chart_name == "expectation_chart") type <- "expectation"
  if (chart_name == "trended_expectation_chart") type <- "trended"

  data <- if (!inherits(plot$data, "waiver")) as.data.frame(plot$data) else {
    candidates <- lapply(plot$layers, function(x) if (!inherits(x$data, "waiver")) as.data.frame(x$data) else NULL)
    candidates <- candidates[vapply(candidates, function(x) !is.null(x) && nrow(x), logical(1))]
    if (length(candidates)) candidates[[1]] else data.frame()
  }
  if (!nrow(data)) return(NULL)
  x <- if ("observation" %in% names(data)) "observation" else if ("date" %in% names(data)) "date" else names(data)[1]
  group <- if (".plot_group" %in% names(data)) ".plot_group" else NULL
  labels <- plot_labels_code(plot)
  header <- c("# Readable ggplot2 code generated by policycraft", "library(ggplot2)", "library(dplyr)", "", readable_data_code(data), "")
  aes_group <- if (!is.null(group)) paste0(", group = `", group, "`") else ""
  base <- paste0("chart <- ggplot(chart_data, aes(x = `", x, "`, y = value", aes_group, "))")

  body <- switch(type,
    run = c(
      "median_value <- median(chart_data$value, na.rm = TRUE)", "", base,
      "chart <- chart + geom_line(colour = \"darkgray\", linewidth = 1.2)",
      "chart <- chart + geom_point(colour = \"blue\", size = 2.5)",
      "chart <- chart + geom_hline(yintercept = median_value, colour = \"blue\", linewidth = 1)",
      "chart <- chart + annotate(\"text\", x = min(chart_data[[1]], na.rm = TRUE), y = median_value, label = paste(\"Median:\", round(median_value, 2)), vjust = -0.7, hjust = 0)"
    ),
    line = c(base, "chart <- chart + geom_line(colour = \"steelblue\", linewidth = 1.3)", "chart <- chart + geom_point(colour = \"steelblue\", size = 3.5)"),
    bar = c(
      "chart <- ggplot(chart_data, aes(x = reorder(`.plot_group`, value), y = value, fill = `.plot_group`))",
      "chart <- chart + geom_col(width = 0.7, alpha = 0.8)",
      "chart <- chart + geom_text(aes(label = round(value, 2)), hjust = -0.1, fontface = \"bold\")",
      "chart <- chart + coord_flip() + guides(fill = \"none\")"
    ),
    expectation = c(
      "# The limit and signal columns below are the values calculated by Policycraft.", base,
      "chart <- chart + geom_line(colour = \"darkgray\", linewidth = 1.2)",
      "chart <- chart + geom_point(aes(colour = sigma_signals), size = 2.5)",
      if ("emp_cl_orig" %in% names(data)) c(
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` < recalc_date, emp_cl_orig, NA)), colour = \"blue\")",
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` >= recalc_date, emp_cl_recalc, NA)), colour = \"green\")",
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` < recalc_date, emp_ucl_orig, NA)), colour = \"red\")",
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` < recalc_date, emp_lcl_orig, NA)), colour = \"red\")",
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` >= recalc_date, emp_ucl_recalc, NA)), colour = \"red\", linetype = \"dashed\")",
        "chart <- chart + geom_line(aes(y = ifelse(`.chart_x` >= recalc_date, emp_lcl_recalc, NA)), colour = \"red\", linetype = \"dashed\")",
        "chart <- chart + geom_vline(xintercept = unique(chart_data$recalc_date), colour = \"purple\", linetype = \"dotted\")",
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_cl_orig[1], label = paste0(\"Original CL (\", round(chart_data$emp_cl_orig[1], 2), \")\"), colour = \"blue\", size = 4, fontface = \"bold\", hjust = 0, vjust = -0.8)"),
        paste0("chart <- chart + annotate(\"text\", x = unique(chart_data$recalc_date), y = chart_data$emp_cl_recalc[1], label = paste0(\"Recalculated CL (\", round(chart_data$emp_cl_recalc[1], 2), \")\"), colour = \"green4\", size = 4, fontface = \"bold\", hjust = 0, vjust = -0.8)"),
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_ucl_orig[1], label = paste0(\"Original UCL (\", round(chart_data$emp_ucl_orig[1], 2), \")\"), colour = \"red\", hjust = 0, vjust = -0.6)"),
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_lcl_orig[1], label = paste0(\"Original LCL (\", round(chart_data$emp_lcl_orig[1], 2), \")\"), colour = \"red\", hjust = 0, vjust = 1.4)"),
        paste0("chart <- chart + annotate(\"text\", x = unique(chart_data$recalc_date), y = chart_data$emp_ucl_recalc[1], label = paste0(\"Recalculated UCL (\", round(chart_data$emp_ucl_recalc[1], 2), \")\"), colour = \"red\", hjust = 0, vjust = -0.6)"),
        paste0("chart <- chart + annotate(\"text\", x = unique(chart_data$recalc_date), y = chart_data$emp_lcl_recalc[1], label = paste0(\"Recalculated LCL (\", round(chart_data$emp_lcl_recalc[1], 2), \")\"), colour = \"red\", hjust = 0, vjust = 1.4)")
      ) else c(
        "chart <- chart + geom_line(aes(y = emp_cl), colour = \"blue\")",
        "chart <- chart + geom_line(aes(y = emp_ucl), colour = \"red\")",
        "chart <- chart + geom_line(aes(y = emp_lcl), colour = \"red\")",
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_cl[1], label = paste0(\"CL (\", round(chart_data$emp_cl[1], 2), \")\"), colour = \"blue\", size = 4, fontface = \"bold\", hjust = 0, vjust = -0.8)"),
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_ucl[1], label = paste0(\"UCL (\", round(chart_data$emp_ucl[1], 2), \")\"), colour = \"red\", size = 4, fontface = \"bold\", hjust = 0, vjust = -0.6)"),
        paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$emp_lcl[1], label = paste0(\"LCL (\", round(chart_data$emp_lcl[1], 2), \")\"), colour = \"red\", size = 4, fontface = \"bold\", hjust = 0, vjust = 1.4)")
      ),
      "chart <- chart + scale_colour_manual(values = c(`TRUE` = \"red\", `FALSE` = \"blue\"))"
    ),
    trended = c(
      "# Refit the trend so the main statistical construction is visible and editable.",
      paste0("chart_data$trend_position <- as.numeric(chart_data$`", x, "` - min(chart_data$`", x, "`))"),
      "trend_model <- lm(value ~ trend_position, data = chart_data)",
      "chart_data$trended_cl <- predict(trend_model)",
      "trend_sigma <- sd(residuals(trend_model), na.rm = TRUE) / 1.128",
      "chart_data$trended_ucl <- chart_data$trended_cl + 3 * trend_sigma",
      "chart_data$trended_lcl <- chart_data$trended_cl - 3 * trend_sigma", "", base,
      "chart <- chart + geom_line(colour = \"darkgray\", linewidth = 1.2)",
      "chart <- chart + geom_point(aes(colour = sigma_signals), size = 2.5)",
      "chart <- chart + geom_line(aes(y = trended_cl), colour = \"blue\")",
      "chart <- chart + geom_line(aes(y = trended_ucl), colour = \"red\", linetype = \"dotted\")",
      "chart <- chart + geom_line(aes(y = trended_lcl), colour = \"red\", linetype = \"dotted\")",
      paste0("chart <- chart + annotate(\"text\", x = min(chart_data$`", x, "`), y = chart_data$trended_cl[1], label = paste0(\"Trended CL (\", round(chart_data$trended_cl[1], 2), \")\"), colour = \"blue\", hjust = 0, vjust = -0.8)"),
